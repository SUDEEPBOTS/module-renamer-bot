func NormalizeToASCII(text string) string {
	var sb strings.Builder
	for _, r := range text {
		if mapped, ok := UnicodeLookalikeMap[r]; ok {
			sb.WriteRune(mapped)
		} else {
			sb.WriteRune(r)
		}
	}
	return sb.String()
}

func NormalizeRune(r rune) rune {
	if mapped, ok := UnicodeLookalikeMap[r]; ok {
		return mapped
	}
	return r
}

type CaseVariant struct {
	Original   string
	Upper      string
	Lower      string
	Title      string
	Camel      string
	Snake      string
	Kebab      string
	Normalized string
}

func NewCaseVariant(word string) CaseVariant {
	norm := strings.TrimSpace(word)
	upper := strings.ToUpper(norm)
	lower := strings.ToLower(norm)
	title := toTitleCase(lower)

	return CaseVariant{
		Original:   word,
		Upper:      upper,
		Lower:      lower,
		Title:      title,
		Normalized: NormalizeToASCII(word),
	}
}
